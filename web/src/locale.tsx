export const Locale = createContext("en");
export function useWords() {
  const language = useContext(Locale);
  return (k: Key) =>
    dictionaries[language]?.[k] ||
    phrases[k]?.[["en", "ar", "ur", "hi", "th"].indexOf(language)] ||
    en[k];
}
export type Word = Key;
